import type { Database } from 'bun:sqlite';

// Postgres mirror of the SQLite schema at POSTGRES_BASELINE_VERSION. SQLite migrations stay the
// source of truth: a new SQLite migration fails postgresSchema.test.ts until its Postgres
// counterpart is added to POSTGRES_SCHEMA_MIGRATIONS below.
// Types: INTEGER -> BIGINT, AUTOINCREMENT keys -> identity columns, COLLATE NOCASE -> lower().
export const POSTGRES_BASELINE_VERSION = 14;

