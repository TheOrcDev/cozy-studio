function now() {
  return new Date().toISOString();
}

export function migratePostgresDatabase(database: Database) {
  database.run(`CREATE TABLE IF NOT EXISTS schema_migrations (
    version BIGINT PRIMARY KEY, name TEXT NOT NULL, applied_at TEXT NOT NULL)`);
  database.run(`CREATE TABLE IF NOT EXISTS hosted_migrations (
    version BIGINT PRIMARY KEY, name TEXT NOT NULL, applied_at TEXT NOT NULL)`);

  const applied = new Set(
    (
      database.query('SELECT version FROM schema_migrations').all() as Array<{ version: number }>
    ).map((row) => Number(row.version)),
  );
  const appliedHosted = new Set(
    (
      database.query('SELECT version FROM hosted_migrations').all() as Array<{ version: number }>
    ).map((row) => Number(row.version)),
  );

  database.transaction(() => {
    if (!applied.has(POSTGRES_BASELINE_VERSION)) {
      for (const ddl of BASELINE_DDL) database.run(ddl);
      for (let version = 1; version <= POSTGRES_BASELINE_VERSION; version += 1) {
        database
          .query('INSERT INTO schema_migrations (version, name, applied_at) VALUES (?, ?, ?)')
          .run(version, `postgres_baseline_v${POSTGRES_BASELINE_VERSION}`, now());
      }
    }
    for (const migration of HOSTED_MIGRATIONS) {
      if (appliedHosted.has(migration.version)) continue;
      for (const ddl of migration.ddl) database.run(ddl);
      database
        .query('INSERT INTO hosted_migrations (version, name, applied_at) VALUES (?, ?, ?)')
        .run(migration.version, migration.name, now());
    }
    for (const migration of POSTGRES_SCHEMA_MIGRATIONS) {
      if (applied.has(migration.version)) continue;
      for (const ddl of migration.ddl) database.run(ddl);
      database
        .query('INSERT INTO schema_migrations (version, name, applied_at) VALUES (?, ?, ?)')
        .run(migration.version, `postgres_v${migration.version}`, now());
    }
  })();
}

export function latestPostgresSchemaVersion() {
  return POSTGRES_SCHEMA_MIGRATIONS.at(-1)?.version ?? POSTGRES_BASELINE_VERSION;
}
